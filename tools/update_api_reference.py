"""Generate a callable lookup from source without importing any transports."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/reference/python/symbols.md"
SECTIONS = {
    "Cloud": {
        "cloud/auth.py": ("MysaAuth",),
        "cloud/client.py": ("MysaClient",),
    },
    "HomeKit": {
        "homekit/controller.py": ("HomeKitProtocol", "PairingSession"),
        "homekit/device.py": ("HomeKitDevice",),
    },
    "MQTT": {"mqtt/client.py": ("MysaMqttClient",)},
    "Runtime and domain helpers": {
        "cloud/device_commands.py": (),
        "cloud/reconciliation.py": ("PendingCommand", "PendingCommandTracker"),
        "cloud/validation.py": (),
        "cloud/schedule_workflow.py": (
            "ScheduleWorkflow",
            "ScheduleJournal",
            "ScheduleTransport",
            "MysaScheduleTransport",
        ),
        "cloud/holds.py": (),
        "cloud/account_workflow.py": (),
        "runtime/state.py": ("DeviceView",),
        "runtime/routing.py": ("CommandRouter", "LocalTransport"),
        "runtime/telemetry.py": ("MqttTelemetryState", "MqttLiveStatusRenewal"),
    },
}


def callables(
    tree: ast.Module, classes: tuple[str, ...]
) -> list[tuple[str, ast.FunctionDef | ast.AsyncFunctionDef]]:
    """Select public module functions and methods on the documented classes."""
    result = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if not node.name.startswith("_"):
                result.append((node.name, node))
        elif isinstance(node, ast.ClassDef) and node.name in classes:
            result.extend(
                (f"{node.name}.{method.name}", method)
                for method in node.body
                if isinstance(method, (ast.FunctionDef, ast.AsyncFunctionDef))
                and (
                    not method.name.startswith("_")
                    or method.name in {"__init__", "__aenter__", "__aexit__"}
                )
            )
    return result


def render() -> str:
    """Build a source-derived lookup; behavioral contracts remain hand-written."""
    lines = [
        "# Python callable lookup",
        "",
        "Generated by `python tools/update_api_reference.py`; do not edit by hand.",
        "This lookup records current signatures and the first docstring line.",
        "Consult the [Python contracts](../../README.md#python-api-contracts) for",
        "lifecycle, errors and behavior. Properties appear with their getter",
        "signature; access them as attributes. Constructor `self` parameters are",
        "shown as declared in source. Dataclass fields and response-model shapes",
        "remain in the linked source and topic references.",
        "",
        "- [Cloud exports](#cloud-exports)",
        *[f"- [{name}](#{name.lower().replace(' ', '-')})" for name in SECTIONS],
        "",
        "## Cloud exports",
        "",
        "The following names are exported from `mysa_client.cloud`. Supported",
        "submodule helpers are listed in the [cloud contract](cloud.md#public-api-and-integration-helpers).",
        "",
    ]
    tree = ast.parse((ROOT / "src/mysa_client/cloud/__init__.py").read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__all__"
            for target in node.targets
        ):
            names = ast.literal_eval(node.value)
            lines.extend(f"- `{name}`" for name in names)

    for title, modules in SECTIONS.items():
        lines.extend(["", f"## {title}", ""])
        for module, classes in modules.items():
            path = ROOT / "src/mysa_client" / module
            relative = f"../../../src/mysa_client/{module}"
            lines.extend(
                [
                    f"### `mysa_client.{module[:-3].replace('/', '.')}`",
                    "",
                    f"[Source]({relative})",
                    "",
                    "| Callable | Declared signature and return type | Purpose |",
                    "| --- | --- | --- |",
                ]
            )
            for name, node in callables(ast.parse(path.read_text()), classes):
                prefix = "async " if isinstance(node, ast.AsyncFunctionDef) else ""
                signature = f"{prefix}({ast.unparse(node.args)})"
                if node.returns:
                    signature += f" -> {ast.unparse(node.returns)}"
                doc = (ast.get_docstring(node) or "See source contract.").splitlines()[
                    0
                ]
                signature = signature.replace("|", r"\|")
                doc = doc.replace("|", r"\|").replace("`", "")
                lines.append(
                    f"| [{name}]({relative}#L{node.lineno}) | `{signature}` | {doc} |"
                )
            lines.append("")
    lines.extend(["[Documentation index](../../README.md)", ""])
    return "\n".join(lines)


def main() -> int:
    """Write the index or reject stale generated content in CI."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print("API reference is stale; run python tools/update_api_reference.py")
            return 1
        print("Python callable reference is up to date.")
        return 0
    OUTPUT.write_text(expected)
    print("Updated Python callable reference.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
